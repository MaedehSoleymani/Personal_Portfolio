// عناصر صفحه
const langToggle = document.getElementById("langToggle");
const menuToggle = document.getElementById("menuToggle");
const nav = document.querySelector(".main-nav");


// تغییر زبان سایت
function setLanguage(lang) {
  const dict = translations[lang] || translations.en;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  document.body.dir = lang === "fa" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = dict[key];

    if (value !== undefined) {
      element.innerHTML = value;
    }
  });

  langToggle.innerHTML = lang === "en"
    ? 'FA <span>↗</span>'
    : 'EN <span>↗</span>';

  menuToggle.setAttribute(
    "aria-label",
    lang === "fa" ? "باز کردن منو" : "Open menu"
  );

  localStorage.setItem("portfolio-language", lang);
}


// زبان ذخیره‌شده کاربر
const savedLanguage = localStorage.getItem("portfolio-language");

setLanguage(savedLanguage === "fa" ? "fa" : "en");


// دکمه تغییر زبان
langToggle.addEventListener("click", () => {
  const currentLanguage = document.documentElement.lang;
  const newLanguage = currentLanguage === "en" ? "fa" : "en";

  setLanguage(newLanguage);

  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
});


// منوی موبایل
menuToggle.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("open");

  menuToggle.setAttribute("aria-expanded", String(isOpen));
});


// بستن منو بعد از انتخاب یکی از لینک‌ها
nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});


// نمایش تدریجی بخش‌ها هنگام اسکرول
const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  },
  {
    threshold: 0.12
  }
);


// فعال‌سازی انیمیشن برای عناصر دارای کلاس reveal
document.querySelectorAll(".reveal").forEach((element) => {
  observer.observe(element);
});
